#!/usr/bin/env python3
"""Build src/pieces/spxdata.js: a monthly S&P 500 total-return series (dividends reinvested, USD) for the
calculator page. Per month: [month-end value, lowest daily close, highest daily close].

  1988-01 onwards  the official total-return index (^SP500TR), daily closes
  1927-12 .. 1987  daily closes of the price index (^GSPC) plus Shiller's monthly dividends
                   (12-month dividends / 12 credited at each month end), scaled to meet the official index

usage: python3 tools/spx_monthly.py <dir with gspc.json, sp500tr.json> <shiller data.csv> <as-of YYYY-MM-DD> [out.js]
  the two json files come from tools/fetch_yahoo.mjs; data.csv is
  https://raw.githubusercontent.com/datasets/s-and-p-500/main/data/data.csv (Robert Shiller's table)
"""
import csv
import datetime as dt
import json
import sys


def load(path, asof):
    r = json.load(open(path))['chart']['result'][0]
    out = []
    for t, v in zip(r['timestamp'], r['indicators']['quote'][0]['close']):
        if v is None:
            continue
        d = (dt.datetime(1970, 1, 1) + dt.timedelta(seconds=t)).date()
        if d <= asof:
            out.append((d, v))
    return out


def monthly(rows):
    """{(y, m): [end, low, high]} from daily closes"""
    out = {}
    for d, v in rows:
        k = (d.year, d.month)
        if k not in out:
            out[k] = [v, v, v]
        else:
            e = out[k]
            e[0] = v
            e[1] = min(e[1], v)
            e[2] = max(e[2], v)
    return out


def main():
    src, shiller, asof = sys.argv[1], sys.argv[2], dt.date.fromisoformat(sys.argv[3])
    dest = sys.argv[4] if len(sys.argv) > 4 else 'src/pieces/spxdata.js'
    px = load(f'{src}/gspc.json', asof)
    tr = load(f'{src}/sp500tr.json', asof)
    div = {}
    for row in csv.DictReader(open(shiller)):
        y, m = int(row['Date'][:4]), int(row['Date'][5:7])
        div[(y, m)] = float(row['Dividend'])
    pm = monthly(px)
    tm = monthly(tr)
    keys = sorted(pm)
    assert keys[0] == (1927, 12)
    # price-based total return up to the end of 1987 (base: Dec 1927 = 1)
    syn = {keys[0]: [1.0, 1.0, 1.0]}
    prev_p, prev_t = pm[keys[0]][0], 1.0
    for k in keys[1:]:
        if k >= (1988, 1):
            break
        e, lo, hi = pm[k]
        d = div[k] / 12
        syn[k] = [prev_t * (e + d) / prev_p, prev_t * lo / prev_p, prev_t * hi / prev_p]
        prev_p, prev_t = e, syn[k][0]
    # join: the official index's first day (1988-01-04) against the last price close of 1987
    first_tr = tr[0][1]
    first_px = next(v for d, v in px if d == tr[0][0])
    tr_end_1987 = first_tr / (first_px / pm[(1987, 12)][0])
    scale = tr_end_1987 / syn[(1987, 12)][0]
    series = []
    for k in keys:
        if k < (1988, 1):
            series.append([x * scale for x in syn[k]])
        else:
            series.append(list(tm[k]))
    last = px[-1][0]
    flat = ','.join(f'{float(f"{x:.5g}"):g}' for row in series for x in row)
    with open(dest, 'w') as f:
        f.write('/* Generated by tools/spx_monthly.py — do not edit by hand.\n')
        f.write('   S&P 500 total return (dividends reinvested, USD), one triple per month from Dec 1927:\n')
        f.write('   month-end value, lowest daily close of the month, highest daily close of the month.\n')
        f.write('   1988 onwards: the official total-return index; earlier: price index + Shiller dividends. */\n')
        f.write(f'export const SPX_ASOF = [{last.year}, {last.month}, {last.day}];\n')
        f.write(f'export const SPX_M = [{flat}];\n')
    # checks printed for a quick comparison with published figures
    ends = {k: s[0] for k, s in zip(keys, series)}
    for y in (1928, 1931, 1933, 1954, 1974, 1987, 1988, 2008, 2022, 2025):
        print(y, f'{(ends[(y, 12)] / ends[(y - 1, 12)] - 1) * 100:+.1f}%')
    n = (2025 - 1927)
    print('1928-2025 annualised', f'{((ends[(2025, 12)] / ends[(1927, 12)]) ** (1 / n) - 1) * 100:.2f}%')
    peak, worst = 0, (0, None)
    for k, s in zip(keys, series):
        dd = s[1] / peak - 1 if peak else 0
        if dd < worst[0]:
            worst = (dd, k)
        peak = max(peak, s[2])
    print('deepest fall', f'{worst[0] * 100:.1f}%', worst[1], '| months', len(series), '| as of', last, '| bytes', len(flat))


main()
